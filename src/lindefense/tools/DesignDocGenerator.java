        w.println();
        w.println("The original game-design document referenced by the master prompt was not available, so every");
        w.println("number below (tower costs, stats, upgrade paths, abilities, enemy rewards/lives/resistances,");
        w.println("boss pools and all 100 wave compositions) was authored for this implementation. All of it lives in");
        w.println("the data classes named above and can be replaced without touching game logic.");
        w.println();
        w.println("## Contents");
        w.println("1. [Global rules](#1-global-rules)");
        w.println("2. [Towers](#2-towers)");
