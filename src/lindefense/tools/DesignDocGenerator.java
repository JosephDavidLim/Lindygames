    private static String hitSummary(TowerStats s) {
        HitSpec h = s.hit;
        List<String> parts = new ArrayList<>();
        switch (s.kind) {
            case PROJECTILE: parts.add("projectile " + f(s.projectileSpeed) + " px/s" + (s.splashRadius > 0 ? ", splash " + f(s.splashRadius) : "")); break;
            case INSTANT: parts.add(s.pierce > 1 ? "beam through line" : "instant beam"); break;
            case CHAIN: parts.add("chain +" + s.chainHops + " hops within " + f(s.chainRange)); break;
            case PULSE: parts.add("pulse (all in range)"); break;
            default: parts.add("support only"); break;
        }
        if (s.targets > 1) parts.add(s.targets + " targets");
        if (s.projectilesPerShot > 1) parts.add(s.projectilesPerShot + " shots");
        if (s.bounces > 0) parts.add(s.bounces + " bounces/" + f(s.bounceRange));
        if (s.clones > 0) parts.add("clones x" + s.clones);
        if (s.heavyEvery > 0) parts.add("every " + s.heavyEvery + "th pulse: stun " + f(s.heavyStun) + "s" + (s.heavyKnockback > 0 ? ", drag " + f(s.heavyKnockback) : ""));
        if (s.resonancePer > 0) parts.add("+1 dmg per " + s.resonancePer + " enemies (max +" + s.resonanceCap + ")");
        if (s.stackCap > 0) parts.add("stacks +" + f(s.stackStep) + "/hit up to " + s.stackCap + (s.stackLinger > 0 ? ", linger " + f(s.stackLinger) + "s" : ""));
        if (h.slowFraction > 0) parts.add("slow " + pct(h.slowFraction) + " " + f(h.slowDuration) + "s");
        if (h.stunDuration > 0) parts.add("stun " + f(h.stunDuration) + "s");
        if (h.knockback > 0) parts.add("knockback " + f(h.knockback) + (h.bossKnockback > 0 ? " (boss " + f(h.bossKnockback) + ")" : ""));
        if (h.armorPierce > 0) parts.add("armour pierce " + pct(h.armorPierce));
        if (h.armorBreak > 0) parts.add("armour break " + pct(h.armorBreak) + " " + f(h.armorBreakDuration) + "s");
        if (h.ignoresResistance) parts.add("ignores immunities");
        if (h.markBonus > 0) parts.add("mark +" + pct(h.markBonus) + " " + f(h.markDuration) + "s");
        if (h.disruptDuration > 0) parts.add("disrupt " + f(h.disruptDuration) + "s");
        if (h.bonusVsBoss != 0) parts.add((h.bonusVsBoss > 0 ? "+" : "") + pct(h.bonusVsBoss) + " vs bosses");
        if (h.bonusVsFortified != 0) parts.add((h.bonusVsFortified > 0 ? "+" : "") + pct(h.bonusVsFortified) + " vs Fortified");
        if (h.bonusVsNonFortified != 0) parts.add("+" + pct(h.bonusVsNonFortified) + " vs non-Fortified");
        if (h.bonusVsComplex != 0) parts.add("+" + pct(h.bonusVsComplex) + " vs complex (base HP >= 6 / bosses)");
        if (h.bonusVsFast != 0) parts.add("+" + pct(h.bonusVsFast) + " vs fast (>= 1.8x)");
        if (h.bonusVsSplitters != 0) parts.add("+" + pct(h.bonusVsSplitters) + " vs splitters");
        if (h.pctMaxHp > 0) parts.add("+" + pct(h.pctMaxHp) + " max HP (cap " + f(h.pctCap) + ")");
        if (h.stripsFortified) parts.add("strips Fortified");
        if (s.seesCamo) parts.add("camo detection");
        if (s.auraRange > 0) {
            List<String> a = new ArrayList<>();
            if (s.auraRate > 0) a.add("+" + pct(s.auraRate) + " speed" + (s.auraRateMilitary > 0 ? " (Military +" + pct(s.auraRateMilitary) + ")" : ""));
            if (s.auraDamage > 0) a.add("+" + pct(s.auraDamage) + " damage");
            if (s.auraRangeBonus > 0) a.add("+" + pct(s.auraRangeBonus) + " range");
            if (s.auraDetection) a.add("camo detection");
            if (s.auraSurveillanceImmunity) a.add("Surveillance immunity");
            parts.add("aura " + f(s.auraRange) + ": " + String.join(", ", a));
        }
        if (s.auraEnemySlow > 0) parts.add("wind wall slow " + pct(s.auraEnemySlow));
        if (s.incomePerWave > 0) parts.add("income $" + f(s.incomePerWave) + "/wave");
        if (s.summonCount > 0) parts.add("summons " + s.summonCount + " Sprite(s) every " + f(s.summonInterval) + "s for " + f(s.summonLifetime) + "s");
        return String.join("; ", parts);
    }

