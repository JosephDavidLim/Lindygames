    private static String children(EnemyType e) {
        if (!e.hasChildren()) return "-";
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < e.getChildTypes().length; i++) {
            if (i > 0) sb.append(" + ");
            sb.append(e.getChildCounts()[i]).append(" x ").append(e.getChildTypes()[i].displayName);
        }
        return sb.toString();
    }

    private static String resist(EnemyType e) {
        List<String> r = new ArrayList<>();
        if (e.getArmor() > 0) r.add("armour " + pct(e.getArmor()));
        if (e.getWeakHitThreshold() > 0) r.add("hits < " + e.getWeakHitThreshold() + " dmg halved");
        if (e.isPhysicalImmune()) r.add("Physical-immune");
        if (e.resistance(lindefense.combat.DamageType.EXPLOSIVE) < 1) r.add("Explosive x" + f(e.resistance(lindefense.combat.DamageType.EXPLOSIVE)));
        if (e.hasInnateCamo()) r.add("always Camo");
        return r.isEmpty() ? "-" : String.join(", ", r);
    }

    private static String mechanic(EnemyType e) {
        switch (e.mechanic) {
            case ACCELERATE_ON_DAMAGE: return "+15% speed per hit taken (max +90%)";
            case BUBBLE_SWAP: return "every 3 s swaps track position with the nearest enemy ahead within 45 px";
            case SELECTION_FRONT: return "every 2.5 s jumps 6 px ahead of the furthest enemy within 140 px in front";
            case INSERTION_LEAPFROG: return "every 2 s leapfrogs 6 px past the nearest enemy within 70 px in front";
            case SHELL_GAP_JUMP: return "every 3 s jumps forward by its gap: 140, 70, 35, then 18 px";
            case HEAP_SHIELD: return "enemies on its route up to 90 px behind it take 50% damage; itself Physical-immune";
            case RADIX_PHASES: return "layers 8-7 plain; 6-5 Physical-immune; 4-3 Energy & Magic -50%; 2-1 Explosive-immune";
            case BUCKET_STORE: return "every 1 s stores non-boss enemies with base HP <= 5 within 30 px (max 6); releases them on death; leaks them if it leaks";
            default:
                if (e == EnemyType.SINGLY_LINKED_LIST) return "fast";
                if (e == EnemyType.TIMSORT) return "fast + splits into Merge Sort and Insertion Sort";
                if (e.hasChildren()) return "splits when destroyed";
                return "-";
        }
    }

